def load_fixture() -> dict:
    return json.loads(gzip.decompress(FIXTURE.read_bytes()).decode("utf-8"))


def max_difference(a, b) -> float:
    if a is None or b is None:
        if a is not b:
            raise AssertionError(f"{a!r} vs {b!r}")
        return 0.0
    if isinstance(a, (int, float)):
        return abs(a - b)
    if len(a) != len(b):
        raise AssertionError(f"length {len(a)} vs {len(b)}")
    return max((max_difference(x, y) for x, y in zip(a, b)), default=0.0)


class SpecTests(unittest.TestCase):
    def test_layout_sizes(self):
        self.assertEqual(LAYOUT.points_per_frame, 120)
        self.assertEqual(LAYOUT.features_per_frame, 971)
        self.assertEqual(len(feature_names()), 971)
        self.assertEqual(len(set(feature_names())), 971)

    def test_face_subset_is_unique_and_inside_the_478_point_mesh(self):
        self.assertEqual(len(set(LAYOUT.face_indices)), 69)
        self.assertTrue(all(0 <= index < 468 for index in LAYOUT.face_indices))

    def test_every_face_and_pose_point_has_a_mirror_partner_or_is_on_the_midline(self):
        face_midline = {17, 0, 14, 13, 1, 10, 152}
        for index in LAYOUT.face_indices:
            partner = LAYOUT.face_mirror.get(index, index)
            self.assertIn(partner, LAYOUT.face_indices, index)
            self.assertEqual(partner == index, index in face_midline, index)
        for index in LAYOUT.pose_indices:
            self.assertIn(LAYOUT.pose_mirror.get(index, index), LAYOUT.pose_indices)

    def test_face_sets_match_mediapipe_connection_lists_when_mediapipe_is_installed(self):
        try:
            from mediapipe.tasks.python.vision import FaceLandmarksConnections as faces
        except ImportError as error:
            self.skipTest(f"mediapipe is not installed: {error}")
        groups = next(part for part in SPEC["parts"] if part["name"] == "face")["groups"]

        def members(connections):
            return {index for connection in connections for index in (connection.start, connection.end)}

        self.assertEqual(set(groups["lips_outer"]) | set(groups["lips_inner"]), members(faces.FACE_LANDMARKS_LIPS))
        self.assertEqual(set(groups["left_eyebrow"]), members(faces.FACE_LANDMARKS_LEFT_EYEBROW))
        self.assertEqual(set(groups["right_eyebrow"]), members(faces.FACE_LANDMARKS_RIGHT_EYEBROW))
        self.assertLessEqual({263, 362}, members(faces.FACE_LANDMARKS_LEFT_EYE))
        self.assertLessEqual({33, 133}, members(faces.FACE_LANDMARKS_RIGHT_EYE))


class GoldenV2Tests(unittest.TestCase):
    """Python must reproduce the committed fixture (it was generated by Python, so this catches drift)."""

    @classmethod
    def setUpClass(cls):
        cls.fixture = load_fixture()

    def test_fixture_is_current_and_large_enough(self):
        self.assertEqual(self.fixture["spec_version"], SPEC["spec_version"])
        self.assertGreaterEqual(self.fixture["frame_count"], 1000)
        self.assertEqual(self.fixture["frame_count"], sum(len(s["frames"]) for s in self.fixture["sequences"]))

    def test_fixture_covers_every_hand_assignment_path(self):
        codes = {case["expected"]["hand_assignment"] for case in self.fixture["canonicalize_cases"]}
        self.assertEqual(codes, set(ASSIGNMENT_CODES.values()))
        self.assertTrue(any(not s["reference"]["from_pose"] for s in self.fixture["sequences"]))

    def test_python_reproduces_canonical_frames(self):
        for case in self.fixture["canonicalize_cases"]:
            actual = canonicalize_frame(case["raw"])
            self.assertEqual(actual["hand_assignment"], case["expected"]["hand_assignment"], case["id"])
            self.assertEqual(max_difference(
                [actual[k] for k in ("left_hand", "right_hand", "pose", "pose_visibility", "face")],
                [case["expected"][k] for k in ("left_hand", "right_hand", "pose", "pose_visibility", "face")],
            ), 0.0, case["id"])

    def test_python_reproduces_sequence_checksums_and_vectors(self):
        weights = [((i * 7919) % 1009) / 1009.0 - 0.5 for i in range(971)]
        for sequence in self.fixture["sequences"]:
            result = sequence_features(sequence["frames"])
            self.assertEqual(result["reference"], sequence["reference"], sequence["id"])
            for index, row in enumerate(result["features"]):
                checks = [sum(row), sum(abs(v) for v in row), sum(v * w for v, w in zip(row, weights))]
                self.assertEqual(max_difference(checks, sequence["checksums"][index]), 0.0, f"{sequence['id']} {index}")
                if str(index) in sequence["full_vectors"]:
                    self.assertEqual(max_difference(row, sequence["full_vectors"][str(index)]), 0.0)


class JavaScriptParityTests(unittest.TestCase):
    """Run the browser implementation under Node and compare every value of every fixture frame."""

    def test_javascript_matches_python_on_every_value(self):
        node = shutil.which("node")
        if not node:
            self.skipTest("Node.js is not installed, so the JavaScript implementation cannot be run")
        completed = subprocess.run([node, str(DUMP_SCRIPT)], cwd=ROOT, capture_output=True, text=True, timeout=300)
        self.assertEqual(completed.returncode, 0, completed.stderr)
        js = json.loads(completed.stdout)
        fixture = load_fixture()
        tolerance = fixture["tolerance"]
        worst = 0.0
        for case, actual in zip(fixture["canonicalize_cases"], js["canonical"], strict=True):
            expected = canonicalize_frame(case["raw"])
            self.assertEqual(actual["hand_assignment"], expected["hand_assignment"], case["id"])
            for key in ("left_hand", "right_hand", "pose", "pose_visibility", "face"):
                worst = max(worst, max_difference(actual[key], expected[key]))
        values = 0
        for sequence, actual in zip(fixture["sequences"], js["sequences"], strict=True):
            expected = sequence_features(sequence["frames"])
            self.assertEqual(actual["reference"]["from_pose"], expected["reference"]["from_pose"])
            worst = max(worst, max_difference(actual["reference"]["origin"], expected["reference"]["origin"]))
            for row_js, row_py in zip(actual["features"], expected["features"], strict=True):
                worst = max(worst, max_difference(row_js, row_py))
                values += len(row_py)
        self.assertGreaterEqual(values, 1000 * 971)
        self.assertLessEqual(worst, tolerance)
        print(f"\n  features v2 parity: {fixture['frame_count']} frames, {values} values, largest |JS - Python| = {worst:.3g}", file=sys.stderr)


def body_truth(seed: int = 7, width: int = 640, height: int = 480, keep: dict | None = None) -> dict:
    import random
    return Body(random.Random(seed), width, height).frame(0.5, keep or {})


class CanonicalFrameTests(unittest.TestCase):
    def test_mirrored_and_unmirrored_input_give_the_same_canonical_frame(self):
        for seed in range(25):
            truth = body_truth(seed, *[(640, 480), (480, 640)][seed % 2])
            plain = canonicalize_frame(raw_from_truth(truth, 10, *[(640, 480), (480, 640)][seed % 2], mirrored=False, label_mode="normal"))
            mirrored = canonicalize_frame(raw_from_truth(truth, 10, *[(640, 480), (480, 640)][seed % 2], mirrored=True, label_mode="normal"))
            for key in ("left_hand", "right_hand", "pose", "pose_visibility", "face"):
                self.assertLess(max_difference(plain[key], mirrored[key]), 1e-9, (seed, key))

    def test_pose_assignment_overrides_wrong_handedness_labels(self):
        truth = body_truth(3)
        frame = canonicalize_frame(raw_from_truth(truth, 1, 640, 480, mirrored=False, label_mode="wrong"))
        self.assertEqual(frame["hand_assignment"], ASSIGNMENT_CODES["pose"])
        self.assertEqual(frame["left_hand"], truth["left"])
        self.assertEqual(frame["right_hand"], truth["right"])

    def test_without_pose_labels_are_swapped_for_unmirrored_input(self):
        truth = body_truth(4, keep={"pose": False})
        frame = canonicalize_frame(raw_from_truth(truth, 1, 640, 480, mirrored=False, label_mode="normal"))
        self.assertEqual(frame["hand_assignment"], ASSIGNMENT_CODES["label"])
        self.assertEqual(frame["left_hand"], truth["left"])
        raw = raw_from_truth(truth, 1, 640, 480, mirrored=False, label_mode="normal")
        self.assertEqual({hand["handedness"] for hand in raw["hands"]}, {"Left", "Right"})
        left_raw = next(hand for hand in raw["hands"] if hand["landmarks"] == truth["left"])
        self.assertEqual(left_raw["handedness"], "Right", "MediaPipe calls the signer's left hand 'Right' on unmirrored input")

    def test_conflicting_labels_fall_back_to_image_position(self):
        truth = body_truth(5, keep={"pose": False})
        frame = canonicalize_frame(raw_from_truth(truth, 1, 640, 480, mirrored=False, label_mode="same"))
        self.assertEqual(frame["hand_assignment"], ASSIGNMENT_CODES["position"])
        self.assertLess(frame["right_hand"][0][0], frame["left_hand"][0][0])

    def test_no_hands(self):
        truth = body_truth(6, keep={"left": False, "right": False})
        frame = canonicalize_frame(raw_from_truth(truth, 1, 640, 480, mirrored=False, label_mode="normal"))
        self.assertEqual(frame["hand_assignment"], ASSIGNMENT_CODES["none"])
        self.assertIsNone(frame["left_hand"])
        self.assertIsNone(frame["right_hand"])

    def test_bad_input_is_rejected(self):
        raw = raw_from_truth(body_truth(8), 1, 640, 480, mirrored=False, label_mode="normal")
        for change in ({"timestamp_ms": 1.5}, {"image_width": 0}, {"pose": raw["pose"][:20]}, {"face": raw["face"][:400]}):
            with self.assertRaises(ValueError, msg=change):
                canonicalize_frame({**raw, **change})
        bad_hand = copy.deepcopy(raw)
        bad_hand["hands"][0]["landmarks"] = bad_hand["hands"][0]["landmarks"][:20]
        with self.assertRaises(ValueError):
            canonicalize_frame(bad_hand)
        nan = copy.deepcopy(raw)
        nan["pose"][3][0] = float("nan")
        with self.assertRaises(ValueError):
            canonicalize_frame(nan)


class SequenceFeatureTests(unittest.TestCase):
    def frames(self, count=3, keep=None, step=40):
        out = []
        for index in range(count):
            import random
            truth = Body(random.Random(11), 640, 480).frame(index * step / 1000.0, keep or {})
            out.append(canonicalize_frame(raw_from_truth(truth, 1000 + index * step, 640, 480, False, "normal")))
        return out

    def test_shoulder_midpoint_is_the_origin_and_shoulder_width_the_unit(self):
        frames = self.frames(1)
        row = sequence_features(frames)["features"][0]
        base = (2 * 21) * 3
        ls = row[base + 1 * 3: base + 1 * 3 + 2]
        rs = row[base + 2 * 3: base + 2 * 3 + 2]
        self.assertAlmostEqual((ls[0] + rs[0]) / 2, 0.0, places=12)
        self.assertAlmostEqual((ls[1] + rs[1]) / 2, 0.0, places=12)
        self.assertAlmostEqual(((ls[0] - rs[0]) ** 2 + (ls[1] - rs[1]) ** 2) ** 0.5, 1.0, places=12)

    def test_velocity_is_position_change_per_second(self):
        frames = self.frames(2, step=50)
        rows = sequence_features(frames)["features"]
        names = feature_names()
        i_pos = names.index("pos.right_hand[8].x")
        i_vel = names.index("vel.right_hand[8].x")
        self.assertEqual(rows[0][i_vel], 0.0)
        self.assertAlmostEqual(rows[1][i_vel], (rows[1][i_pos] - rows[0][i_pos]) / 0.05, places=9)

    def test_hand_shape_keeps_handedness(self):
        frame = self.frames(1)[0]
        frame["left_hand"] = [[1.0 - x, y, z] for x, y, z in frame["right_hand"]]
        row = sequence_features([frame])["features"][0]
        names = feature_names()
        left = row[names.index("shape.left_hand[0].x"): names.index("shape.left_hand[0].x") + 63]
        right = row[names.index("shape.right_hand[0].x"): names.index("shape.right_hand[0].x") + 63]
        self.assertNotEqual(left, right)
        self.assertLess(max(abs(a + b) for a, b in zip(left[0::3], right[0::3])), 1e-9)

    def test_missing_parts_are_zero_and_masked(self):
        frames = self.frames(2, keep={"left": False, "face": False})
        row = sequence_features(frames)["features"][1]
        names = feature_names()
        self.assertEqual(row[names.index("mask.left_hand")], 0.0)
        self.assertEqual(row[names.index("mask.face")], 0.0)
        self.assertEqual(row[names.index("mask.right_hand")], 1.0)
        for name, value in zip(names, row):
            if "left_hand" in name or "face" in name.split("-")[-1] or name.startswith(("pos.face", "vel.face")):
                if not name.startswith("mask."):
                    self.assertEqual(value, 0.0, name)

    def test_reference_falls_back_without_a_pose(self):
        frames = self.frames(3, keep={"pose": False})
        reference = sequence_reference(frames)
        self.assertFalse(reference["from_pose"])
        self.assertEqual(reference["origin"], [320.0, 240.0])
        self.assertEqual(reference["scale"], 120.0)
        self.assertEqual(sequence_features(frames)["features"][0][-1], 0.0)

    def test_timestamps_must_increase(self):
        frames = self.frames(2)
        frames[1]["timestamp_ms"] = frames[0]["timestamp_ms"]
        with self.assertRaises(ValueError):
            sequence_features(frames)
        with self.assertRaises(ValueError):
            sequence_features([])


